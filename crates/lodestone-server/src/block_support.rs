    /// One assertion per family shape, collected rather than asserted in the
    /// loop so a broken arm does not hide the other five.
    #[test]
    fn each_family_reads_the_cell_vanilla_reads() {
        let p = pos();
        let cases: Vec<(&str, &str, Requirement)> = vec![
            // A floor torch's support is below.
            (
                "floor torch",
                "minecraft:torch",
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
            // A wall torch's support is the wall it points away from.
            // `facing=east` means the wall is west.
            (
                "wall torch",
                "minecraft:wall_torch[facing=east]",
                Requirement::Supported(BlockPos::new(p.x - 1, p.y, p.z)),
            ),
            // A lever's `face=floor` connects UP, so the support is below.
            (
                "floor lever",
                "minecraft:lever[face=floor,facing=north]",
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
            // `face=ceiling` connects DOWN, so the support is above.
            (
                "ceiling lever",
                "minecraft:lever[face=ceiling,facing=north]",
                Requirement::Supported(BlockPos::new(p.x, p.y + 1, p.z)),
            ),
            // A rail's support is below.
            (
                "rail",
                "minecraft:rail[shape=north_south]",
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
            // A door's upper arm: the cell below must be the same door's
            // lower half.
            (
                "door upper half",
                "minecraft:oak_door[half=upper,facing=north]",
                Requirement::Partner {
                    pos: BlockPos::new(p.x, p.y - 1, p.z),
                    block: "minecraft:oak_door".to_string(),
                    property: "half",
                    value: "lower",
                },
            ),
            // A bed's foot looks along `facing`, and `facing=south` is +z.
            (
                "bed foot",
                "minecraft:red_bed[part=foot,facing=south]",
                Requirement::Partner {
                    pos: BlockPos::new(p.x, p.y, p.z + 1),
                    block: "minecraft:red_bed".to_string(),
                    property: "part",
                    value: "head",
                },
            ),
            // A hanging sign hangs from the cell above.
            (
                "ceiling hanging sign",
                "minecraft:oak_hanging_sign[rotation=0]",
                Requirement::Supported(BlockPos::new(p.x, p.y + 1, p.z)),
            ),
            // A hanging lantern's support is above.
            (
                "hanging lantern",
                "minecraft:lantern[hanging=true]",
                Requirement::Supported(BlockPos::new(p.x, p.y + 1, p.z)),
            ),
            (
                "standing lantern",
                "minecraft:lantern[hanging=false]",
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
        ];
        let mut mismatches = Vec::new();
        for (label, state, expected) in cases {
            let got = requirement(p, state);
            if got.as_ref() != Some(&expected) {
                mismatches.push(format!("{label}: expected {expected:?}, got {got:?}"));
            }
        }
        assert!(mismatches.is_empty(), "{mismatches:#?}");
    }

    /// The two directions of [`survives`] for one support cell, so the
    /// predicate is shown to be able to answer both ways rather than being
    /// constant.
    #[test]
    fn a_plant_survives_on_dirt_and_not_on_air_or_water() {
        let p = pos();
        let below = BlockPos::new(p.x, p.y - 1, p.z);
        let with = |fill: &'static str| {
            move |cell: BlockPos| {
                if cell == below {
                    fill.to_string()
                } else {
                    "minecraft:air".to_string()
                }
            }
        };
        assert!(survives(p, "minecraft:poppy", with("minecraft:dirt")));
        assert!(!survives(p, "minecraft:poppy", with("minecraft:air")));
        assert!(
            !survives(p, "minecraft:poppy", with("minecraft:water[level=0]")),
            "a fluid is not a support"
        );
        // And the un-modelled majority is unaffected in both worlds.
        assert!(survives(p, "minecraft:stone", with("minecraft:air")));
    }

    /// A bed's partner test is on identity, not on presence: a *different*
    /// bed colour, or the same `part`, must both fail. The same-`part` case is
    /// the one a "is there a bed next door" implementation gets wrong.
    #[test]
    fn a_bed_half_needs_the_opposite_half_of_the_same_bed() {
        let p = pos();
        let partner = BlockPos::new(p.x, p.y, p.z + 1);
        let with = |fill: &'static str| {
            move |cell: BlockPos| {
                if cell == partner {
                    fill.to_string()
                } else {
                    "minecraft:air".to_string()
                }
            }
        };
        let foot = "minecraft:red_bed[part=foot,facing=south]";
        let mut wrong = Vec::new();
        if !survives(p, foot, with("minecraft:red_bed[part=head,facing=south]")) {
            wrong.push("the matching head must support the foot");
        }
        if survives(p, foot, with("minecraft:red_bed[part=foot,facing=south]")) {
            wrong.push("two feet must not support each other");
        }
        if survives(p, foot, with("minecraft:blue_bed[part=head,facing=south]")) {
            wrong.push("a different bed block must not count as the partner");
        }
        if survives(p, foot, with("minecraft:stone")) {
            wrong.push("an ordinary block must not count as the partner");
        }
        assert!(wrong.is_empty(), "{wrong:#?}");
    }
