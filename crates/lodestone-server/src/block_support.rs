//! Which cell a block is standing on, and whether it is still there — the
//! real "can this block survive here" rule, reduced to the one question a
//! neighbour update has to answer: *did my support just go away?*
//!
//! # What it is
//!
//! Vanilla destroys a block when its support leaves: many block families'
//! own shape-update reaction resolves to air, and the block placement rule
//! then drops the block's loot and writes air. Nothing in this crate did
//! that: `crate::neighbor_update` propagated notifications faithfully and
//! every reaction it dispatched (`crate::random_tick::react_to_notification`)
//! was a redstone or gravity one, so **no block anywhere reacted to losing
//! its support** — torches, flowers, rails, doors, beds and sugar cane were
//! all unbreakable-by-support.
//!
//! This module answers "which cell supports this state" ([`requirement`]) and
//! "is that cell still good" ([`survives`]). `crate::server`'s `destroy_block`
//! drives the cascade and owns the drops.
//!
//! # How the per-block rule is derived
//!
//! Not by hand. [`support_kind`] was generated by walking the decompiled
//! 26.2 source's block registrations and the inheritance chain each one
//! sits in, then mapping each block to the nearest ancestor whose own
//! survival check is a self-destruct on one *named* support cell. The
//! families and their support shapes:
//!
//! | family | support cell | kind |
//! |---|---|---|
//! | flowers, saplings, crops, stems, mushrooms, grass, dead bush, nether wart, seagrass, corals | `pos.below()` | [`SupportKind::Below`] |
//! | torches (floor), rails, snow layers, carpets, pressure plates, redstone wire, diodes (repeaters/comparators), sugar cane, cactus, bamboo, sea pickles, standing signs, banners | `pos.below()` | [`SupportKind::Below`] |
//! | wall torches, ladders, wall signs, wall hanging signs, wall banners, tripwire hooks, cocoa, amethyst clusters, wall coral fans | the wall the block is attached to, opposite its facing | [`SupportKind::AttachedFacing`] |
//! | buttons, levers, grindstone | the `face`/`facing` mount | [`SupportKind::AttachFace`] |
//! | doors, double plants (tall grass, sunflower, ...), pitcher crop, small dripleaf | lower: below; upper: the lower half | [`SupportKind::DoubleBlock`] |
//! | beds | the partner half | [`SupportKind::BedPart`] |
//! | ceiling hanging signs, hanging roots, cave vines, weeping vines (plant part) | `pos.above()` | [`SupportKind::Hanging`] |
//! | lanterns | `hanging` decides above vs below | [`SupportKind::HangingOrBelow`] |
//!
//! The generator's judgement was checked family by family against the
//! decompile, and the checks changed the table: skulls (floor and wall),
//! tripwire, turtle eggs and sniffer eggs declare **no** survival check
//! anywhere in their ancestor chains in 26.2, so a floor skull and a turtle
//! egg stay put when the block under them goes, and inheriting a "below"
//! rule for them would have been a visible new bug.
//!
//! # The one approximation, and its direction
//!
//! The real support test is a *geometric* predicate over the block's own
//! support shape — either "rigid" or "centre" support depending on the
//! family — which no census in this repo carries.
//! `lodestone_data::snow_support::face_full_up` is the neighbouring question
//! (a full-face test over the **collision** shape) and it is measurably not
//! the same one: read out of the committed JVM dump, farmland reports
//! `false` for all 8 of its states and soul sand `false` for its only one,
//! while crops and rails sit on both quite happily.
//!
//! So this module does **not** ask how sturdy the support is. It asks whether
//! the support cell went to **air or a fluid** ([`crate::chunk::is_air_or_fluid`]),
//! which is a strict subset of the real rule and therefore fails in the safe
//! direction: a block whose support was destroyed pops (the reported case), and
//! a block sitting on a *weak* support — a torch on a fence, a rail on a hopper
//! — is left alone rather than wrongly destroyed. Closing the gap means a
//! rigid/centre support-shape census in `lodestone-data`; until then the
//! deviation is one-directional and named.
//!
//! Two blocks are excluded for the same reason from the other side: `lily_pad`
//! and `frogspawn` are supported *by water*, so an "air or fluid" trigger
//! would destroy every one of them on sight.
//!
//! # How to change it
//!
//! To add a family, add its shared ancestor to the generator's base table and
//! regenerate — do not hand-add a block name, because the inheritance chain is
//! what makes the 291 rows below trustworthy. To *remove* one, check the
//! family really has no survival check first; the five removals above were
//! each grepped.
//!
//! Deliberately not covered: the kelp/weeping-and-twisting-vines head/body
//! pair (its own growth direction, and a survival check that reads the
//! *body* chain), climbing vines and multiface growths (any of five faces,
//! not one named cell), scaffolding (a distance count), chorus plants,
//! pointed dripstone, big dripleaf stems (reads above *and* below) and mossy
//! carpet (a `bottom`/side-wall variant set). Each is a real family with a
//! real rule; none of them is a *single* support cell, which is what this
//! module's shape can express.

