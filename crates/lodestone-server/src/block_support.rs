/// The one cell `state` at `pos` depends on, or `None` when nothing about this
/// block's existence is conditional.
#[must_use]
pub(crate) fn requirement(pos: BlockPos, state: StateId) -> Option<Requirement> {
    let block = state.block();
    let below = BlockPos::new(pos.x, pos.y - 1, pos.z);
    let above = BlockPos::new(pos.x, pos.y + 1, pos.z);
    match support_kind(block)? {
        SupportKind::Below => Some(Requirement::Supported(below)),
        SupportKind::Hanging => Some(Requirement::Supported(above)),
        SupportKind::HangingOrBelow => {
            // `hanging` ? UP : DOWN, and the survival check reads the cell
            // that direction's *opposite* leads to.
            let hanging = get_str_property(state, PropertyKey::Hanging)
                == Some(BuiltinPropertyValue::True);
            Some(Requirement::Supported(if hanging { above } else { below }))
        }
        SupportKind::AttachedFacing => {
            // The cell opposite the block's own facing direction. A state naming no
            // `facing` is not a legal wall variant, so there is nothing to check.
            let facing = direction_from_property(get_str_property(state, PropertyKey::Facing)?)?;
            Some(Requirement::Supported(facing.opposite().relative(pos)))
        }
        SupportKind::AttachFace => {
            // `crate::redstone::attached_connected_direction` computes exactly
            // this connected direction; the survival check looks the other way.
            let connected = attached_connected_direction(state);
            Some(Requirement::Supported(connected.opposite().relative(pos)))
        }
        SupportKind::DoubleBlock => match get_str_property(state, PropertyKey::Half) {
            // The upper arm's rule: the cell below must be this same block
            // with `half=lower`.
            Some(BuiltinPropertyValue::Upper) => Some(Requirement::Partner {
                pos: below,
                block,
                property: PropertyKey::Half,
                value: BuiltinPropertyValue::Lower,
            }),
            // The lower arm is the ordinary support test. A state naming no
            // `half` is treated as the lower half, which is what the default
            // state of every block in this family is.
            _ => Some(Requirement::Supported(below)),
        },
        SupportKind::BedPart => {
            // The foot looks along `facing`, the head against it. Both halves
            // fail to air when the partner is not there, which is what makes
            // breaking one end break the other.
            let facing = direction_from_property(get_str_property(state, PropertyKey::Facing)?)?;
            let (partner_dir, want) = match get_str_property(state, PropertyKey::Part) {
                Some(BuiltinPropertyValue::Head) => (facing.opposite(), BuiltinPropertyValue::Foot),
                _ => (facing, BuiltinPropertyValue::Head),
            };
            Some(Requirement::Partner {
                pos: partner_dir.relative(pos),
                block,
                property: PropertyKey::Part,
                value: want,
            })
        }
    }
}

/// Whether `state` at `pos` still has its support, reading the world through
/// `block_at`.
///
/// `true` for every block this crate models no rule for, so this is safe to ask
/// of an arbitrary cell.
pub(crate) fn survives<F>(pos: BlockPos, state: StateId, block_at: F) -> bool
where
    F: Fn(BlockPos) -> WorldState,
{
    let Some(requirement) = requirement(pos, state) else {
        return true;
    };
    match requirement {
        Requirement::Supported(cell) => !is_air_or_fluid_id(block_at(cell)),
        Requirement::Partner {
            pos: cell,
            block,
            property,
            value,
        } => {
            let partner = block_at(cell);
            partner.block() == block && get_str_property(partner, property) == Some(value)
        }
    }
}

/// Returns the support rule for every block family with one named support cell.

#[cfg(test)]
mod tests {
    use super::*;

    fn pos() -> BlockPos {
        BlockPos::new(4, 70, -9)
    }

    #[test]
    fn every_supported_block_is_builtin() {
        assert_eq!(
            Block::all().filter(|&block| support_kind(block).is_some()).count(),
            291
        );
    }

    #[test]
    fn unsupported_blocks_are_absent() {
        for block in [
            Block::SkeletonSkull,
            Block::ZombieHead,
            Block::TurtleEgg,
            Block::SnifferEgg,
            Block::Tripwire,
            Block::LilyPad,
            Block::Frogspawn,
            Block::Stone,
            Block::Dirt,
            Block::Cobweb,
            Block::Vine,
            Block::Scaffolding,
        ] {
            assert!(support_kind(block).is_none(), "unexpected support rule for {block:?}");
        }
    }

    /// The blocks whose ancestors declare no survival check must answer
    /// `None` — they were removed from the generator's output deliberately,
    /// and a regression here means skulls start popping off floors.
    #[test]
    fn blocks_with_no_vanilla_can_survive_are_absent() {
        let mut wrongly_present = Vec::new();
        for block in [
            Block::SkeletonSkull,
            Block::ZombieHead,
            Block::TurtleEgg,
            Block::SnifferEgg,
            Block::Tripwire,
            Block::LilyPad,
            Block::Frogspawn,
            Block::Stone,
            Block::Dirt,
            Block::Cobweb,
            Block::Vine,
            Block::Scaffolding,
        ] {
            if support_kind(block).is_some() {
                wrongly_present.push(block);
            }
        }
        assert!(
            wrongly_present.is_empty(),
            "these have no single-cell survival check in 26.2: {wrongly_present:?}"
        );
    }

    /// One assertion per family shape, collected rather than asserted in the
    /// loop so a broken arm does not hide the other five.
    #[test]
    fn each_family_reads_the_cell_vanilla_reads() {
        let p = pos();
        let cases: Vec<(&str, StateId, Requirement)> = vec![
            // A floor torch's support is below.
            (
                "floor torch",
                state("minecraft:torch"),
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
            // A wall torch's support is the wall it points away from.
            // `facing=east` means the wall is west.
            (
                "wall torch",
                state("minecraft:wall_torch[facing=east]"),
                Requirement::Supported(BlockPos::new(p.x - 1, p.y, p.z)),
            ),
            // A lever's `face=floor` connects UP, so the support is below.
            (
                "floor lever",
                state("minecraft:lever[face=floor,facing=north]"),
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
            // `face=ceiling` connects DOWN, so the support is above.
            (
                "ceiling lever",
                state("minecraft:lever[face=ceiling,facing=north]"),
                Requirement::Supported(BlockPos::new(p.x, p.y + 1, p.z)),
            ),
            // A rail's support is below.
            (
                "rail",
                state("minecraft:rail[shape=north_south]"),
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
            // A door's upper arm: the cell below must be the same door's
            // lower half.
            (
                "door upper half",
                state("minecraft:oak_door[half=upper,facing=north]"),
                Requirement::Partner {
                    pos: BlockPos::new(p.x, p.y - 1, p.z),
                    block: Block::OakDoor,
                    property: PropertyKey::Half,
                    value: BuiltinPropertyValue::Lower,
                },
            ),
            // Small dripleaf has the same upper/lower partner rule as the
            // other two-cell plants, even though its lower half also carries
            // direction and water state.
            (
                "small dripleaf upper half",
                state("minecraft:small_dripleaf[half=upper,facing=north,waterlogged=false]"),
                Requirement::Partner {
                    pos: BlockPos::new(p.x, p.y - 1, p.z),
                    block: Block::SmallDripleaf,
                    property: PropertyKey::Half,
                    value: BuiltinPropertyValue::Lower,
                },
            ),
            // A bed's foot looks along `facing`, and `facing=south` is +z.
            (
                "bed foot",
                state("minecraft:red_bed[part=foot,facing=south]"),
                Requirement::Partner {
                    pos: BlockPos::new(p.x, p.y, p.z + 1),
                    block: Block::RedBed,
                    property: PropertyKey::Part,
                    value: BuiltinPropertyValue::Head,
                },
            ),
            // A hanging sign hangs from the cell above.
            (
                "ceiling hanging sign",
                state("minecraft:oak_hanging_sign[rotation=0]"),
                Requirement::Supported(BlockPos::new(p.x, p.y + 1, p.z)),
            ),
            // A hanging lantern's support is above.
            (
                "hanging lantern",
                state("minecraft:lantern[hanging=true]"),
                Requirement::Supported(BlockPos::new(p.x, p.y + 1, p.z)),
            ),
            (
                "standing lantern",
                state("minecraft:lantern[hanging=false]"),
                Requirement::Supported(BlockPos::new(p.x, p.y - 1, p.z)),
            ),
        ];
        let mut mismatches = Vec::new();
        for (label, state, expected) in cases {
            let got = requirement(p, state);
            if got.as_ref() != Some(&expected) {
                mismatches.push(format!("{label}: expected {expected:?}, got {got:?}"));
            }
        }
        assert!(mismatches.is_empty(), "{mismatches:#?}");
    }

    /// The two directions of [`survives`] for one support cell, so the
    /// predicate is shown to be able to answer both ways rather than being
    /// constant.
    #[test]
    fn a_plant_survives_on_dirt_and_not_on_air_or_water() {
        let p = pos();
        let below = BlockPos::new(p.x, p.y - 1, p.z);
        let with = |fill: &'static str| {
            move |cell: BlockPos| {
                if cell == below {
                    state(fill)
                } else {
                    state("minecraft:air")
                }
            }
        };
        assert!(survives(p, state("minecraft:poppy"), with("minecraft:dirt")));
        assert!(!survives(p, state("minecraft:poppy"), with("minecraft:air")));
        assert!(
            !survives(p, state("minecraft:poppy"), with("minecraft:water[level=0]")),
            "a fluid is not a support"
        );
        // And the un-modelled majority is unaffected in both worlds.
        assert!(survives(p, state("minecraft:stone"), with("minecraft:air")));
    }

    /// A bed's partner test is on identity, not on presence: a *different*
    /// bed colour, or the same `part`, must both fail. The same-`part` case is
    /// the one a "is there a bed next door" implementation gets wrong.
    #[test]
    fn a_bed_half_needs_the_opposite_half_of_the_same_bed() {
        let p = pos();
        let partner = BlockPos::new(p.x, p.y, p.z + 1);
        let with = |fill: &'static str| {
            move |cell: BlockPos| {
                if cell == partner {
                    state(fill)
                } else {
                    state("minecraft:air")
                }
            }
        };
        let foot = state("minecraft:red_bed[part=foot,facing=south]");
        let mut wrong = Vec::new();
        if !survives(p, foot, with("minecraft:red_bed[part=head,facing=south]")) {
            wrong.push("the matching head must support the foot");
        }
        if survives(p, foot, with("minecraft:red_bed[part=foot,facing=south]")) {
            wrong.push("two feet must not support each other");
        }
        if survives(p, foot, with("minecraft:blue_bed[part=head,facing=south]")) {
            wrong.push("a different bed block must not count as the partner");
        }
        if survives(p, foot, with("minecraft:stone")) {
            wrong.push("an ordinary block must not count as the partner");
        }
        assert!(wrong.is_empty(), "{wrong:#?}");
    }

    fn state(text: &str) -> StateId {
        StateId::from_state_str(text).expect("fixture state must resolve")
    }
}
