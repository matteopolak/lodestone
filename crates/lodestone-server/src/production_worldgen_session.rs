async fn generate_request_yielding<S, P>(
    source: &S,
    session: &mut GenerationSession,
) -> Result<PacketSnapshot, SessionError>
where
    S: RegionGenerationSource<Policy = P>,
    P: DimensionPolicy<S>,
{
    if let Some(plan) = target_owned_settlement_plan::<S, P>(session)? {
        let mut region = ProductionGenerationRegion::for_halo(source, &plan.context);
        return region.generate_with_yielding(session).await;
    }
    let mut materializer = LifecycleMaterializer::new(source);
    generate_request_yielding_with_materializer::<S, P>(
        source,
        session,
        &mut materializer,
    )
    .await
}

#[cfg(target_arch = "wasm32")]
async fn generate_request_yielding_with_materializer<'a, S, P>(
    source: &'a S,
    session: &mut GenerationSession,
    materializer: &mut LifecycleMaterializer<&'a S>,
) -> Result<PacketSnapshot, SessionError>
where
    S: LifecycleWorldgenSource + Sync,
    P: DimensionPolicy<S>,
{
    let mut shared_prefixes = SharedPrefixCache::new();
    let mut machine = GenerationStateMachine::<S, P>::new(
        source,
        session,
        materializer,
        &mut shared_prefixes,
        false,
        1,
    )?;
    let executor = PersistentWorldgenExecutor;
    loop {
        if let Some(snapshot) = machine.step(&executor)? {
            return Ok(snapshot);
        }
        crate::chunk::yield_to_browser().await;
    }
}

