impl DimensionPolicy<crate::chunk::OverworldChunkSource> for OverworldPolicy {
    const DIMENSION: Dimension = Dimension::Overworld;

    fn source_schedule() -> SourceSchedule {
        OVERWORLD_SOURCES
    }

    fn prefix_sidecars(
        source: &crate::chunk::OverworldChunkSource,
        coordinate: (i32, i32),
    ) -> Vec<(StageKey, ImmutableSidecar)> {
        vec![
            (
                StageKey::new(Self::DIMENSION, ColumnStage::StructureReferences),
                ImmutableSidecar::new(
                    SidecarKey::StructureReferences,
                    source.lifecycle_structure_references(coordinate.0, coordinate.1),
                ),
            ),
        ]
    }

    fn has_top_layer() -> bool {
        true
    }

    fn target_owned_reverse_settlement() -> bool {
        true
    }

    fn generated_prefix_provenance(
        source: &crate::chunk::OverworldChunkSource,
        coordinate: (i32, i32),
        boundary: ColumnStage,
    ) -> Option<[u8; 32]> {
        source
            .generator()
            .generation_identity()
            .map(|identity| generated_prefix_provenance(identity, coordinate, boundary))
    }

    fn generated_feature_provenance(
        source: &crate::chunk::OverworldChunkSource,
        coordinate: (i32, i32),
    ) -> Option<[u8; 32]> {
        source
            .generator()
            .generation_identity()
            .map(|identity| generated_stage_provenance(identity, coordinate, ColumnStage::Features))
    }

}

