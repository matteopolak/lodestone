const EXECUTOR_VERSION: u32 = 4;

pub(crate) trait DimensionPolicy<S: LifecycleWorldgenSource> {
    const DIMENSION: Dimension;

    fn source_schedule() -> SourceSchedule;

    fn prefix_sidecars(
        source: &S,
        coordinate: (i32, i32),
    ) -> Vec<(StageKey, ImmutableSidecar)>;

    fn has_top_layer() -> bool;

    /// Whether this policy owns a complete FEATURES invocation whose writes
    /// must be settled around requested targets before packet finalization.
    fn target_owned_reverse_settlement() -> bool {
        false
    }

    /// Return an in-process identity for a compact generated prefix when the
    /// source can authenticate every immutable input that affects its bytes.
    /// Dynamic or edited sources return `None` and retain the exact content
    /// digest fallback below.
    fn generated_prefix_provenance(
        _source: &S,
        _coordinate: (i32, i32),
        _boundary: ColumnStage,
    ) -> Option<[u8; 32]> {
        None
    }

    /// Return an authenticated identity for the target's complete FEATURES
    /// result when the source can prove that no edit or dynamic input changed
    /// the generated bytes. The lifecycle falls back to an exact column scan
    /// when this is absent.
    fn generated_feature_provenance(
        _source: &S,
        _coordinate: (i32, i32),
    ) -> Option<[u8; 32]> {
        None
    }

}

