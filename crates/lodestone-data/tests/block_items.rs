// Hermetic tests over the committed table (anchored to the committed dump)
// ---------------------------------------------------------------------------

#[test]
fn committed_table_matches_the_committed_dump_row_for_row() {
    // The strongest check: every entry in the shipped accessor equals what the
    // real server said. Non-vacuous by construction -- it iterates all 1,537
    // items and compares exact strings, so a single transposed row fails.
    let rows = parse_dump(DUMP);
    assert_eq!(
        rows.len(),
        block_items::ITEM_COUNT as usize,
        "dump/table item count mismatch"
    );
    let mut checked_some = 0usize;
    let mut checked_none = 0usize;
    for row in &rows {
        let id = i32::try_from(row.id).expect("item id fits i32");
        // Compared as *names*, so the expected value stays the dump's own
        // string rather than a `Block` this crate produced — the table is typed
        // now, but the anchor must still come from outside it.
        let actual = block_items::block_for_item_id(id).map(Block::name);
        assert_eq!(
            actual,
            row.block.as_deref(),
            "item {} ({}) places the wrong block",
            row.id,
            row.item
        );
        // The name-keyed accessor must agree with the id-keyed one for every
        // item -- otherwise `items::item_id`'s reverse scan has drifted.
        assert_eq!(
            block_items::block_for_item(&row.item),
            row.block.as_deref(),
            "name and id lookups disagree for {}",
            row.item
        );
        if row.block.is_some() {
            checked_some += 1;
        } else {
            checked_none += 1;
        }
    }
    // Both arms must be non-trivially populated, or this test could pass while
    // measuring only one of them.
    assert_eq!(checked_some, 1054, "placeable-item count changed");
    assert_eq!(checked_none, 483, "non-placeable-item count changed");
}

/// Every block this table names must actually exist in the block registry.
/// A typo or a stale block rename would otherwise ship a `set_block` call for
/// a block nothing can resolve.
///
/// # What the `Block` column already guarantees, and what is left for this test
///
/// Half of this assertion is now true by construction: the column is
/// [`Block`]-typed, so it cannot hold a name the *registry* lacks — a bad name
/// fails generation instead. What remains is a genuine cross-table join, and it
/// is the half that was always the real risk: the registry is registration-
/// ordered and the block-*state* table is name-sorted, two independently
/// generated censuses, and this asserts every placeable block appears in both.
#[test]
fn every_placed_block_is_a_real_registered_block() {
    let mut checked = 0usize;
    for id in 0..block_items::ITEM_COUNT {
        let Some(block) = block_items::block_for_item_id(id as i32) else {
            continue;
        };
        let found = (0..lodestone_data::block_states::STATE_COUNT)
            .any(|state| lodestone_data::block_states::block_name(state) == Some(block.name()));
        assert!(found, "item id {id} places {block:?}, which is not a registered block");
        checked += 1;
    }
    assert_eq!(checked, 1054, "expected every placeable item to be checked");
}

/// The exact rows that separate this census from a name match. If someone ever
/// "simplifies" the table into `item_name == block_name`, these fail.
///
/// Both directions are represented: an item whose block has a different name,
/// and an item that places nothing *despite* a block of its name existing.
#[test]
fn the_census_disagrees_with_a_name_match_exactly_where_the_game_does() {
    // False negatives of a name match: real placeable items it would decline.
    for (item, block) in [
        ("minecraft:redstone", "minecraft:redstone_wire"),
        ("minecraft:string", "minecraft:tripwire"),
        ("minecraft:wheat_seeds", "minecraft:wheat"),
        ("minecraft:cocoa_beans", "minecraft:cocoa"),
        ("minecraft:carrot", "minecraft:carrots"),
        ("minecraft:potato", "minecraft:potatoes"),
        ("minecraft:pumpkin_seeds", "minecraft:pumpkin_stem"),
        ("minecraft:melon_seeds", "minecraft:melon_stem"),
    ] {
        assert_eq!(
            block_items::block_for_item(item),
            Some(block),
            "{item} must place {block}"
        );
    }

    // False positives of a name match: a block of this name exists, but the
    // item is not a `BlockItem` and places nothing.
    for item in ["minecraft:wheat", "minecraft:air"] {
        let block_of_that_name = (0..lodestone_data::block_states::STATE_COUNT)
            .any(|state| lodestone_data::block_states::block_name(state) == Some(item));
        assert!(
            block_of_that_name,
            "{item} must still name a real block, or this test proves nothing"
        );
        assert_eq!(
            block_items::block_for_item(item),
            None,
            "{item} names a block but is not a BlockItem, so it must place nothing"
        );
    }
}

/// The ordinary name-match cases, plus the non-placeable direction.
#[test]
fn plain_blocks_resolve_to_themselves_and_tools_resolve_to_nothing() {
    for item in [
        "minecraft:dirt",
        "minecraft:oak_planks",
        "minecraft:white_wool",
        "minecraft:glass",
        "minecraft:cobblestone",
        "minecraft:sand",
        "minecraft:oak_log",
    ] {
        assert_eq!(block_items::block_for_item(item), Some(item), "{item} places itself");
    }

    for item in [
        "minecraft:diamond_sword",
        "minecraft:water_bucket",
        "minecraft:stick",
        "minecraft:bread",
        "minecraft:zombie_spawn_egg",
        "minecraft:flint_and_steel",
    ] {
        assert_eq!(
            block_items::block_for_item(item),
            None,
            "{item} is not a BlockItem and must place nothing"
        );
    }

    // An item this version does not know is a miss, not a panic.
    assert_eq!(block_items::block_for_item("minecraft:not_a_real_item"), None);
    assert_eq!(block_items::block_for_item_id(-1), None);
    assert_eq!(
        block_items::block_for_item_id(block_items::ITEM_COUNT as i32),
        None
    );
}

/// [`block_items::item_for_block`], the inverse this issue's server-side half
/// needs: pairwise-distinct blocks so a transposition in the `OnceLock`
/// build (`table[placed as usize] = ...`) cannot survive, plus the two `None`
/// shapes — a block with no `BlockItem` at all, and an out-of-range `Block`
/// cannot occur since `Block` is exhaustive, so only the first shape is real.
#[test]
fn item_for_block_inverts_block_for_item_id_for_ordinary_blocks() {
    for (item, block_name) in [
        ("minecraft:dirt", "minecraft:dirt"),
        ("minecraft:oak_planks", "minecraft:oak_planks"),
        ("minecraft:diamond_block", "minecraft:diamond_block"),
        ("minecraft:glass", "minecraft:glass"),
    ] {
        let block = Block::from_name(block_name).unwrap_or_else(|| panic!("{block_name} must be a real block"));
        assert_eq!(
            block_items::item_for_block(block).map(lodestone_data::item::Item::name),
            Some(item),
            "item_for_block({block_name}) must invert block_for_item({item})"
        );
    }
}

/// A block no `BlockItem` targets at all — fluids and technical blocks a
/// player can never hold as an item — must report `None` rather than a
/// fabricated item. (`minecraft:redstone_wire` is *not* such a block: the
/// census's own false-negative example, `minecraft:redstone` places it, so
/// `item_for_block` correctly answers `Some(Redstone)` there — this test
/// picks blocks with no `BlockItem` pointing at them by any name.)
#[test]
fn item_for_block_is_none_for_a_block_with_no_block_item() {
    for name in ["minecraft:water", "minecraft:fire", "minecraft:air", "minecraft:nether_portal"] {
        let block = Block::from_name(name).unwrap_or_else(|| panic!("{name} is a real block"));
        assert_eq!(block_items::item_for_block(block), None, "{name} must have no BlockItem");
    }
}

/// Every block this crate's `item_for_block` names must round-trip back
/// through [`block_items::block_for_item_id`] — the property that makes it a
/// true inverse rather than an independently-wrong second table.
#[test]
fn item_for_block_round_trips_through_block_for_item_id_for_every_block() {
    let mut checked = 0usize;
    for block in Block::all() {
        let Some(item) = block_items::item_for_block(block) else {
            continue;
        };
        let item_id = i32::from(item.registry_id());
        assert_eq!(
            block_items::block_for_item_id(item_id),
            Some(block),
            "{item:?} must place {block:?} back"
        );
        checked += 1;
    }
    assert!(checked > 1000, "expected most of the 1,054 placeable blocks to round-trip, got {checked}");
}

