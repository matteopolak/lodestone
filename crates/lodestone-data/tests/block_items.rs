/// Regenerates the committed table from the committed dump and asserts it is
/// byte-identical. `#[ignore]`d because it touches the filesystem under
/// `LODESTONE_REGEN=1`.
#[test]
#[ignore = "regenerates/asserts the committed table; run explicitly"]
fn committed_table_matches_the_committed_dump() {
    let rows = parse_dump(DUMP);
    let rendered = generate(&rows);
    let path = committed_path();

    if std::env::var_os("LODESTONE_REGEN").is_some() {
        std::fs::write(&path, &rendered).expect("write generated table");
        println!("regenerated {} ({} rows)", path.display(), rows.len());
        return;
    }

    let committed = std::fs::read_to_string(&path).expect("read committed table");
    assert_eq!(
        committed, rendered,
        "committed src/generated/block_items.rs has drifted from tests/support/block_items_jvm.txt; \
         regenerate with LODESTONE_REGEN=1"
    );
}
