//! Item → placed-block table: hermetic checks over the committed table, plus
//! an `#[ignore]`d drift guard that regenerates it from the committed JVM dump
//! and asserts byte-for-byte equality (modelled on `hardness.rs` and
//! `item_prototypes.rs`). The generator lives here so the checked-in table can
//! never silently drift from the game data.
//!
//! # Data provenance
//!
//! `tests/support/block_items_jvm.txt` is an authoritative dump produced by
//! booting the real 26.2 server and walking vanilla's own item registry, asking
//! every item that is a block item for its own "get block" accessor — `oracle-java/BlockItemOracle.java`.
//!
//! Neither `registries.json` nor `blocks.json` can answer this: the first is a
//! flat list of item *names* with no item→block relation at all, the second is
//! block properties with no item side. The relation exists only as a field on
//! the `BlockItem` instance, constructed at bootstrap. So, as with collision
//! shapes and hardness, "boot the jar and ask it" is the only authoritative
//! source, and the dump is committed as the external anchor (§ "an expected
//! value must originate outside the code under test").
//!
//! # Refreshing after a version bump
//!
//! 1. Re-dump from the server. Any JDK ≥ 21 with the server jar and its
//!    libraries on the classpath will do — a local JDK:
//!
//! ```text
//! MC="$(cd .cache/mc/26.2 && pwd)"
//! CP="$MC/versions/26.2/server-26.2.jar:$(find "$MC/libraries" -name '*.jar' | tr '\n' ':')"
//! javac -cp "$CP" -d /tmp/oracle crates/lodestone-data/oracle-java/BlockItemOracle.java
//! java -cp "/tmp/oracle:$CP" BlockItemOracle
//! ```
//!
//!    or the temurin Docker classpath the neighbouring oracles document, if no
//!    JDK is installed. Copy its stdout over `tests/support/block_items_jvm.txt`,
//!    keeping the `#` header.
//!
//! 2. Regenerate the committed table:
//!
//! ```text
//! LODESTONE_REGEN=1 cargo test -p lodestone-data --test block_items \
//!     committed_table_matches_the_committed_dump -- --ignored --nocapture
//! ```

use std::fmt::Write as _;
use std::path::PathBuf;

use lodestone_data::block::Block;
use lodestone_data::block_items;

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn committed_path() -> PathBuf {
    manifest_dir().join("src/generated/block_items.rs")
}

/// The committed JVM dump — an external anchor, not gitignored.
const DUMP: &str = include_str!("support/block_items_jvm.txt");

/// One authoritative row: item registry id, item name, and the block it places
/// (`None` for an item that is not a `BlockItem`).
struct Row {
    id: usize,
    item: String,
    block: Option<String>,
}

fn parse_dump(text: &str) -> Vec<Row> {
    let mut rows = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut tok = line.split_whitespace();
        let id: usize = tok.next().expect("id column").parse().expect("id is a usize");
        let item = tok.next().expect("item column").to_owned();
        let block_raw = tok.next().expect("block column");
        assert!(tok.next().is_none(), "unexpected trailing tokens on {line:?}");
        let block = (block_raw != "-").then(|| block_raw.to_owned());
        if let Some(name) = &block {
            assert!(
                name.starts_with("minecraft:"),
                "block column must be a namespaced id or '-', got {name:?}"
            );
        }
        assert!(
            item.starts_with("minecraft:"),
            "item column must be a namespaced id, got {item:?}"
        );
        rows.push(Row { id, item, block });
    }
    rows.sort_by_key(|row| row.id);
    for (index, row) in rows.iter().enumerate() {
        assert_eq!(row.id, index, "dump ids are not a dense 0..N (gap at {index})");
    }
    rows
}

/// Renders the committed `block_items.rs` source from the parsed dump.
fn generate(rows: &[Row]) -> String {
    let count = rows.len();
    let placeable = rows.iter().filter(|row| row.block.is_some()).count();

    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo test -p lodestone-data --test block_items -- --ignored`\n\
         // from tests/support/block_items_jvm.txt (a headless 26.2 server dump of the\n\
         // item registry joined with each block item's own placed-block accessor,\n\
         // protocol 776 / Minecraft 26.2). DO NOT EDIT BY HAND. Regenerate with\n\
         // LODESTONE_REGEN=1 (see the test module docs).\n",
    );
    out.push_str(
        "//! Generated item -> placed-block table for protocol 776 (Minecraft 26.2),\n\
         //! indexed by item network registry id. Consumed by [`crate::block_items`].\n\
         //!\n\
         //! The column holds [`crate::block::Block`] rather than the block's name. Both\n\
         //! spellings are the same fact, but a `&'static str` column costs a pointer and\n\
         //! a length per row plus a relocation each, where the enum costs one `u16` and\n\
         //! resolves to the single copy of the name already in\n\
         //! `BLOCK_REGISTRY_NAMES` — and it cannot hold a string that is not a block.\n\n\
         use crate::block::Block;\n\n",
    );

    let _ = writeln!(out, "/// Number of item entries (ids are `0..ITEM_COUNT`).");
    let _ = writeln!(out, "pub const ITEM_COUNT: u32 = {count};\n");

    let _ = writeln!(
        out,
        "/// The block each item places, indexed by item network registry id; `None`\n\
         /// for the {} of {count} items that are not `BlockItem`s and place nothing.",
        count - placeable
    );
    let _ = writeln!(
        out,
        "pub static BLOCK_FOR_ITEM: [Option<Block>; {count}] = ["
    );
    for row in rows {
        match &row.block {
            Some(block) => {
                // Resolving through `Block::from_name` rather than emitting the
                // camel-cased path directly is deliberate: a name the block
                // registry does not contain fails generation here, naming the
                // item, instead of emitting a variant that does not exist and
                // reporting it as a compile error in a generated file.
                let variant = Block::from_name(block).unwrap_or_else(|| {
                    panic!("item {} places {block}, which is not a built-in block", row.item)
                });
                let _ = writeln!(
                    out,
                    "    Some(Block::{variant:?}), // {} {}",
                    row.id, row.item
                );
            }
            None => {
                let _ = writeln!(out, "    None, // {} {}", row.id, row.item);
            }
        }
    }
    out.push_str("];\n");

    out
}

