/// The load-bearing identity: the enum discriminant *is* the wire's registry
/// id, and the name attached to it is the one the server registered there.
/// Mirrors `block_enum.rs`'s
/// `discriminant_is_the_registry_id_and_names_match_the_server_dump`.
#[test]
fn discriminant_is_the_registry_id_and_names_match_the_server_dump() {
    let rows = parse_dump(DUMP);
    assert_eq!(rows.len(), Item::COUNT as usize, "dump/enum item count");

    let mut mismatches = Vec::new();
    for (id, name) in &rows {
        match Item::from_registry_id(*id) {
            Some(item) => {
                if item.registry_id() != *id || item.name() != name {
                    mismatches.push(format!(
                        "id {id} ({name}): enum gave {:?} = id {} name {}",
                        item,
                        item.registry_id(),
                        item.name()
                    ));
                }
            }
            None => mismatches.push(format!("id {id} ({name}): enum has no such registry id")),
        }
    }
    assert!(
        mismatches.is_empty(),
        "{} of {} items disagree with the dump:\n{}",
        mismatches.len(),
        rows.len(),
        mismatches.join("\n")
    );
    assert_eq!(Item::from_registry_id(Item::COUNT), None);
    assert_eq!(Item::all().len(), rows.len());
}

#[test]
fn name_order_is_also_path_order() {
    let names: Vec<&'static str> = Item::all().map(Item::name).collect();
    let paths: Vec<&'static str> = Item::all().map(Item::path).collect();
    let mut by_name: Vec<usize> = (0..names.len()).collect();
    let mut by_path = by_name.clone();
    by_name.sort_by_key(|&i| names[i]);
    by_path.sort_by_key(|&i| paths[i]);
    assert_eq!(
        by_name, by_path,
        "sorting items by namespaced name and by bare path give different orders; \
         `Item::from_name`'s bare-path search is no longer sound"
    );
}

#[test]
fn names_and_paths_round_trip_through_from_name() {
    let mut failures = Vec::new();
    for item in Item::all() {
        if Item::from_name(item.name()) != Some(item) {
            failures.push(format!("{}: namespaced form did not round-trip", item.name()));
        }
        if Item::from_name(item.path()) != Some(item) {
            failures.push(format!("{}: bare path did not round-trip", item.path()));
        }
        if item.name() != format!("minecraft:{}", item.path()) {
            failures.push(format!("{}: name/path disagree", item.name()));
        }
    }
    assert!(
        failures.is_empty(),
        "{} round-trip failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

#[test]
fn from_name_rejects_foreign_namespaces_and_unknown_paths() {
    assert_eq!(Item::from_name("minecraft:diamond"), Some(Item::Diamond));
    assert_eq!(Item::from_name("diamond"), Some(Item::Diamond));
    assert_eq!(Item::from_name("mypack:diamond"), None);
    assert_eq!(Item::from_name("minecraft:not_an_item"), None);
    assert_eq!(Item::from_name(""), None);
    assert_eq!(Item::from_name("minecraft:"), None);
}

/// The representation claims, as numbers — mirrors `block_enum.rs`'s sibling
/// test. `Option<Item>` costing the same as `Item` is what makes an
/// `[Option<Item>; 1537]` census half the width of `[Option<&str>; 1537]` on a
/// 32-bit target and a quarter on a 64-bit one.
#[test]
fn the_representation_is_the_size_it_claims() {
    assert_eq!(size_of::<Item>(), 2, "Item is a u16 discriminant");
    assert_eq!(
        size_of::<Option<Item>>(),
        2,
        "Option<Item> must use the unused discriminants as its niche"
    );
    assert_eq!(size_of::<ItemRef>(), 4);
}

/// `ItemRef` must cost the built-in path nothing and still carry a custom id
/// losslessly, including at the boundary where the two encodings meet.
#[test]
fn item_ref_separates_builtin_from_custom_without_aliasing() {
    for item in Item::all() {
        let reference = ItemRef::builtin(item);
        assert_eq!(reference.kind(), ItemKind::Builtin(item));
        assert_eq!(reference.builtin_or_none(), Some(item));
    }
    for index in [0u32, 1, 7, 1_000_000, u32::MAX - Item::COUNT as u32] {
        let id = CustomItemId::from_index(index);
        let reference = ItemRef::custom(id);
        assert_eq!(reference.kind(), ItemKind::Custom(id));
        assert_eq!(reference.builtin_or_none(), None);
        assert_eq!(
            reference.kind(),
            ItemKind::Custom(CustomItemId::from_index(index)),
            "custom index {index} did not survive the round trip"
        );
    }
    assert_ne!(
        ItemRef::builtin(Item::from_registry_id(Item::COUNT - 1).expect("last item")),
        ItemRef::custom(CustomItemId::from_index(0)),
        "the last built-in item and the first custom item collided"
    );
}

// ---------------------------------------------------------------------------
// Drift guard (regenerates from the committed dump; needs no external
// artifact beyond it)
// ---------------------------------------------------------------------------

#[test]
#[ignore = "regenerates/verifies the committed enum; run explicitly"]
fn committed_enum_matches_dump() {
    let rows = parse_dump(DUMP);
    let generated = generate(&rows);

    if std::env::var_os("LODESTONE_REGEN").is_some() {
        std::fs::write(committed_path(), &generated).expect("write item enum");
        eprintln!("regenerated {}", committed_path().display());
        return;
    }

    let committed = std::fs::read_to_string(committed_path()).expect("committed item enum present");
    assert_eq!(
        generated, committed,
        "src/generated/item_enum.rs is stale vs the JVM dump; regenerate with LODESTONE_REGEN=1"
    );
}
