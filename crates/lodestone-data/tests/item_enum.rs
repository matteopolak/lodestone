/// The Rust enum variant name for a registry path: `oak_sapling` → `OakSapling`.
///
/// Callers must have already checked the path against
/// [`assert_path_is_variant_safe`]; this function only transforms.
fn variant_name(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for word in path.split('_') {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

/// Fails the generator — loudly, naming the offender — if any item name cannot
/// become a distinct, legal Rust variant. Mirrors
/// `tools.rs`'s `assert_path_is_variant_safe`, whose reasoning applies
/// unchanged: a silently-aliased collision is the dangerous failure mode, not
/// a non-compiling variant. `docs/registry-types.md` already recorded this
/// registry as clean (1,537 paths, 1,537 distinct variants, all
/// `minecraft:`, none digit-leading); asserting it here is what keeps that
/// true after a version bump rather than a fact that happened to hold once.
fn assert_path_is_variant_safe(names: &[String]) -> Vec<(String, String)> {
    let mut seen: BTreeMap<String, String> = BTreeMap::new();
    let mut pairs = Vec::with_capacity(names.len());
    for name in names {
        let (namespace, path) = name
            .split_once(':')
            .unwrap_or_else(|| panic!("registry name {name:?} has no namespace"));
        assert_eq!(
            namespace, "minecraft",
            "the generated enum covers the built-in registry only; {name:?} is not `minecraft:`"
        );
        assert!(
            !path.is_empty()
                && path
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_'),
            "item path {path:?} is outside [a-z0-9_] and has no obvious variant spelling"
        );
        assert!(
            !path.as_bytes()[0].is_ascii_digit(),
            "item path {path:?} starts with a digit, which is not a legal Rust variant"
        );
        let variant = variant_name(path);
        assert_ne!(
            variant, "Self",
            "item path {path:?} camel-cases to the reserved identifier `Self`"
        );
        if let Some(previous) = seen.insert(variant.clone(), path.to_owned()) {
            panic!(
                "item paths {previous:?} and {path:?} both camel-case to `{variant}`; the \
                 generator must be taught a disambiguation rather than silently aliasing them"
            );
        }
        pairs.push((variant, name.clone()));
    }
    pairs
}

/// Renders `src/generated/item_enum.rs`: the `Item` enum whose discriminant
/// **is** the `minecraft:item` registry id, plus the name-lookup index table.
fn generate(rows: &[(u16, String)]) -> String {
    let count = rows.len();
    let names: Vec<String> = rows.iter().map(|(_, name)| name.clone()).collect();
    let variants = assert_path_is_variant_safe(&names);

    let mut by_name: Vec<u16> = (0..count as u16).collect();
    by_name.sort_unstable_by(|&a, &b| names[a as usize].cmp(&names[b as usize]));

    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo test -p lodestone-data --test item_enum -- --ignored`\n\
         // from tests/support/item_prototype_jvm.txt (a headless 26.2 server dump of\n\
         // BuiltInRegistries.ITEM's registration order, protocol 776 / Minecraft 26.2).\n\
         // DO NOT EDIT BY HAND. Regenerate with LODESTONE_REGEN=1 (see the test module\n\
         // docs).\n",
    );
    out.push_str(
        "//! The generated `minecraft:item` registry as a Rust enum.\n\
         //!\n\
         //! One variant per built-in item, in **registration** order, with the\n\
         //! discriminant written out explicitly so that `item as u16` *is* the registry\n\
         //! id a `Holder<Item>` carries on the wire — no lookup, no branch, no table. That\n\
         //! identity is the whole point of the representation: every per-item census in\n\
         //! this crate is a plain array indexed by it.\n\
         //!\n\
         //! The accessors live in [`crate::item`]; this file is data only.\n\n",
    );

    let _ = writeln!(
        out,
        "/// A built-in item of Minecraft 26.2, one variant per `minecraft:item`\n\
         /// registry entry.\n\
         ///\n\
         /// `Item as u16` is the registry id. Ordering is **registration** order, not\n\
         /// alphabetical.\n\
         ///\n\
         /// This enum is intentionally *not* `#[non_exhaustive]` and carries no `Custom`\n\
         /// variant: a match over it is exhaustive, so a version bump that adds an item\n\
         /// fails the compile of every incomplete match instead of falling into a\n\
         /// wildcard. Items a plugin adds are represented by [`crate::item::ItemRef`],\n\
         /// one level out.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n\
         #[repr(u16)]\n\
         pub enum Item {{"
    );
    for (id, (variant, name)) in variants.iter().enumerate() {
        let _ = writeln!(out, "    /// `{name}`\n    {variant} = {id},");
    }
    out.push_str("}\n\n");

    let _ = writeln!(
        out,
        "/// Every [`Item`], indexed by its registry id — the safe inverse of\n\
         /// `item as u16`, and the iteration order of the registry.\n\
         ///\n\
         /// An array rather than a {count}-arm `match` because this crate forbids\n\
         /// `unsafe` (so the transmute is unavailable) and because a table index is one\n\
         /// bounds check where the match is a jump table plus {count} lines for rustc to\n\
         /// chew.\n\
         pub static ITEMS_BY_REGISTRY_ID: [Item; {count}] = ["
    );
    for chunk in variants.chunks(4) {
        out.push_str("    ");
        for (variant, _) in chunk {
            let _ = write!(out, "Item::{variant}, ");
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("];\n\n");

    let _ = writeln!(
        out,
        "/// Registry ids sorted by canonical name, for `O(log {count})` name lookup\n\
         /// against [`crate::generated_items::ITEM_NAMES`].\n\
         ///\n\
         /// A permutation of `u16` rather than a `[(&str, Item)]` pairs table on purpose:\n\
         /// the pairs table would re-introduce {count} fat pointers and their relocations\n\
         /// for names that already exist once in rodata.\n\
         pub static REGISTRY_IDS_BY_NAME: [u16; {count}] = ["
    );
    for chunk in by_name.chunks(16) {
        out.push_str("    ");
        for id in chunk {
            let _ = write!(out, "{id}, ");
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("];\n");
    out
}

