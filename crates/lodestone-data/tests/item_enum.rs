//! `Item` enum: hermetic checks over the committed table, plus an `#[ignore]`d
//! drift guard that regenerates it from the committed JVM dump and asserts
//! byte-for-byte equality — modelled on `tools.rs`'s `generate_block_enum` and
//! `block_enum.rs`'s gates. The generator lives here so the checked-in enum can
//! never silently drift from game data.
//!
//! # Data provenance
//!
//! `tests/support/item_prototype_jvm.txt` is already the committed JVM dump for
//! this registry: `ItemPrototypeOracle.java` walks vanilla's own item registry on
//! the real 26.2 server and writes one `P <registryId> <itemName> …` line per
//! item, in registration order. `tests/item_prototypes.rs`'s
//! `dump_ids_and_names_match_the_registries_json_table` already cross-checked
//! this id/name pairing against Mojang's own `registries.json`
//! (`crate::items::item_name`, generated by `cargo xtask gen-registries`), so
//! the two independently produced artifacts agree on all 1,537 pairs before
//! this file ever runs. This generator reads only the `id`/`name` columns of
//! that same dump; the other columns (stack size, damage, equip slot) are
//! `item_prototypes.rs`'s concern, not this one's.
//!
//! Unlike `generate_block_enum`, there is no default-state table to join in —
//! an item has no analogue of a block state.
//!
//! # Refreshing after a version bump
//!
//! 1. Re-dump `tests/support/item_prototype_jvm.txt` per the recipe in
//!    `tests/item_prototypes.rs`'s module docs.
//! 2. Regenerate the committed enum:
//!
//! ```text
//! LODESTONE_REGEN=1 cargo test -p lodestone-data --test item_enum \
//!     committed_enum_matches_dump -- --ignored --nocapture
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use lodestone_data::item::{CustomItemId, Item, ItemKind, ItemRef};

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn committed_path() -> PathBuf {
    manifest_dir().join("src/generated/item_enum.rs")
}

/// The committed JVM dump — an external anchor, not gitignored. Shared with
/// `tests/item_prototypes.rs`, but parsed independently here.
const DUMP: &str = include_str!("support/item_prototype_jvm.txt");

// ---------------------------------------------------------------------------
// Dump parsing (id + name columns only)
// ---------------------------------------------------------------------------

fn parse_dump(text: &str) -> Vec<(u16, String)> {
    let mut rows: Vec<(u16, String)> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut tok = line.split_whitespace();
        assert_eq!(tok.next(), Some("P"), "unexpected record kind on {line:?}");
        let id: u16 = tok
            .next()
            .expect("id column")
            .parse()
            .expect("id fits u16");
        let name = tok.next().expect("name column").to_owned();
        rows.push((id, name));
    }
    rows.sort_unstable_by_key(|(id, _)| *id);
    for (index, (id, _)) in rows.iter().enumerate() {
        assert_eq!(
            *id as usize, index,
            "dump ids are not a dense 0..N (gap at {index})"
        );
    }
    rows
}

