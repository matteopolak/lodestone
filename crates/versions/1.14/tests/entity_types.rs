#[test]
fn tables_are_non_empty_and_out_of_range_is_none() {
    for protocol in [PROTOCOL_1_14_4, PROTOCOL_1_15_2, PROTOCOL_1_16_5] {
        let table = entity_types::table_for(protocol);
        assert!(table.entity_type_name(12).is_some(), "entity table populated");
        assert_eq!(table.entity_type_name(-1), None);
        assert_eq!(table.entity_type_name(i32::MAX), None);
        // The mob/object aliases resolve through the same unified table.
        assert_eq!(table.mob_type_name(-1), None);
        assert_eq!(table.object_type_name(i32::MAX), None);
        // The rendered count and the rendered array must agree; a hand edit
        // to one half of a generated file is what this catches.
        assert_eq!(table.declared_len(), table.len());
        assert!(!table.is_empty());
    }
}

/// The three registries are genuinely different, and the difference is the
/// kind that produces a real-but-wrong answer rather than an error.
///
/// Ids 0..=3 agree across the era (nothing was inserted before the bat), so
/// the probes are chosen past that: 1.15 inserted the bee at 4 and 1.16 the
/// hoglin at 32. A shared table would name a plausible mob for every spawn
/// packet in the other two protocols.
#[test]
fn the_three_registries_disagree_about_what_a_type_id_means() {
    let name = |protocol: i32, id: i32| {
        entity_types::table_for(protocol)
            .entity_type_name(id)
            .expect("every era member carries these ids")
    };
    assert_eq!(
        [name(PROTOCOL_1_14_4, 4), name(PROTOCOL_1_15_2, 4), name(PROTOCOL_1_16_5, 4)],
        ["minecraft:blaze", "minecraft:bee", "minecraft:bee"]
    );
    assert_eq!(
        [name(PROTOCOL_1_14_4, 32), name(PROTOCOL_1_15_2, 32), name(PROTOCOL_1_16_5, 32)],
        ["minecraft:husk", "minecraft:horse", "minecraft:hoglin"]
    );
    // Counts, measured from the three registries.
    assert_eq!(entity_types::table_for(PROTOCOL_1_14_4).len(), 102);
    assert_eq!(entity_types::table_for(PROTOCOL_1_15_2).len(), 103);
    assert_eq!(entity_types::table_for(PROTOCOL_1_16_5).len(), 108);
}

#[test]
fn known_ids_resolve_to_well_formed_identifiers() {
    // Spot 1.16 unified ids the live seam relies on; a transposed table fails
    // instantly.
    let table = entity_types::table_for(PROTOCOL_1_16_5);
    assert_eq!(table.entity_type_name(12), Some("minecraft:creeper"));
    assert_eq!(table.entity_type_name(59), Some("minecraft:pig"));
    assert_eq!(table.entity_type_name(102), Some("minecraft:zombie"));
    assert_eq!(table.entity_type_name(2), Some("minecraft:arrow"));
    assert_eq!(table.entity_type_name(6), Some("minecraft:boat"));
    assert_eq!(table.entity_type_name(106), Some("minecraft:player"));
    // Both spawn aliases index the unified registry in 1.16.
    assert_eq!(table.mob_type_name(59), Some("minecraft:pig"));
    assert_eq!(table.object_type_name(6), Some("minecraft:boat"));
    assert_eq!(entity_types::PLAYER, "minecraft:player");
}

#[test]
fn identifiers_have_lowercase_paths() {
    for protocol in [PROTOCOL_1_14_4, PROTOCOL_1_15_2, PROTOCOL_1_16_5] {
    let table = entity_types::table_for(protocol);
    for id in 0..256 {
        if let Some(name) = table.entity_type_name(id) {
            let path = name
                .strip_prefix("minecraft:")
                .expect("namespaced identifier");
            assert!(!path.is_empty(), "id {id} has an empty path");
            assert!(
                path.chars().all(|c| c.is_ascii_lowercase()
                    || c.is_ascii_digit()
                    || matches!(c, '_' | '.' | '-' | '/')),
                "id {id} identifier {name:?} has an invalid path character"
            );
            let _key: lodestone_model::ResourceKey = name.parse().expect("valid resource key");
        }
    }
    }
}

