//! Entity-type id→name tables for this era's three protocols: hermetic
//! checks over the committed tables, plus `#[ignore]`d drift guards that
//! regenerate them from their own sources and assert byte-for-byte equality
//! (modelled on the v26-2 entity-type table and the packet-id generator).
//!
//! # Three tables, two sources
//!
//! The registry is dense and alphabetical, so any insertion renumbers
//! everything after it: 1.15 added the bee at id 4 and 1.16 added four nether
//! mobs, leaving 102 / 103 / 108 entries that agree only on ids 0..=3. The
//! 498 and 578 tables are generated from each jar's own `--reports` registry
//! dump, committed under `tests/support/` — an authority. The 754 table
//! predates those dumps here and still comes from `minecraft-data`, a
//! cross-check; it is left on that source rather than regenerated, so this
//! work cannot silently move it.
//!
//! 1.13 flattening **unified** the entity registry: 1.12's two id spaces (a
//! `spawn_mob` mob table and a `spawn_object` object table) collapsed into a
//! single numeric registry that both `spawn_entity` and `spawn_entity_living`
//! index. So there is exactly one table here, not two. The oracle is
//! `minecraft-data` (`vendor/minecraft-data/data/pc/1.16.2/entities.json`,
//! which 1.16.5 shares per `dataPaths.json`; gitignored).
//!
//! `minecraft-data`'s 1.16 `name` fields are already lowercase snake_case, so
//! there is no casing judgement. The `type` field is unreliable in this dump
//! (several 1.16 mobs are tagged `UNKNOWN`), so the generator keys off `id`
//! and includes every entry rather than filtering by category.
//!
//! Regenerate the committed tables after a data bump with:
//!
//! ```text
//! LODESTONE_REGEN=1 cargo test -p lodestone-v1-14 --test entity_types \
//!     committed -- --ignored --nocapture
//! ```

use std::fmt::Write as _;
use std::path::PathBuf;

use lodestone_v1_14::entity_types;
use lodestone_v1_14::{PROTOCOL_1_14_4, PROTOCOL_1_15_2, PROTOCOL_1_16_5};

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Vendored community data (gitignored local artifact). 1.16.5 shares
/// 1.16.2's entity registry per `minecraft-data`'s `dataPaths.json`.
fn source_path() -> PathBuf {
    manifest_dir().join("../../../vendor/minecraft-data/data/pc/1.16.2/entities.json")
}

fn committed_path() -> PathBuf {
    manifest_dir().join("src/generated/entity_types.rs")
}

/// One jar-sourced table: the unmodified `--reports` registry dump and where
/// its rendered table is committed.
struct JarSource {
    minecraft: &'static str,
    protocol: i32,
    dump: &'static str,
    dump_file: &'static str,
    committed: &'static str,
}

const JAR_SOURCES: &[JarSource] = &[
    JarSource {
        minecraft: "1.14.4",
        protocol: PROTOCOL_1_14_4,
        dump: include_str!("support/registries_1_14_4_jar.json"),
        dump_file: "registries_1_14_4_jar.json",
        committed: "src/generated/entity_types_498.rs",
    },
    JarSource {
        minecraft: "1.15.2",
        protocol: PROTOCOL_1_15_2,
        dump: include_str!("support/registries_1_15_2_jar.json"),
        dump_file: "registries_1_15_2_jar.json",
        committed: "src/generated/entity_types_578.rs",
    },
];

/// Parses `minecraft:entity_type` out of a `--reports` registry dump into the
/// same sorted `(id, identifier)` shape [`parse_entities`] produces from
/// `minecraft-data`.
///
/// The report's own `protocol_id` is authoritative and the identifiers are
/// already namespaced, so unlike the `minecraft-data` path there is no
/// casing or prefixing judgement at all.
fn parse_registry_entities(doc: &str) -> Vec<(i32, String)> {
    let value: serde_json::Value = serde_json::from_str(doc).expect("registries.json parses");
    let entries = value["minecraft:entity_type"]["entries"]
        .as_object()
        .expect("registries.json carries minecraft:entity_type entries");
    let mut pairs: Vec<(i32, String)> = entries
        .iter()
        .map(|(name, entry)| {
            let id = entry["protocol_id"]
                .as_i64()
                .expect("entry has an integer protocol_id") as i32;
            (id, name.clone())
        })
        .collect();
    pairs.sort_by_key(|(id, _)| *id);
    for (index, (id, _)) in pairs.iter().enumerate() {
        assert_eq!(
            *id as usize, index,
            "entity_type protocol ids are not dense from 0"
        );
    }
    pairs
}

/// Renders one jar-sourced table.
fn generate_from_jar(source: &JarSource, pairs: &[(i32, String)]) -> String {
    let JarSource {
        minecraft,
        protocol,
        dump_file,
        ..
    } = *source;

    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo test -p lodestone-v1-14 --test entity_types -- --ignored`\n",
    );
    let _ = writeln!(out, "// from tests/support/{dump_file} (protocol {protocol} /");
    let _ = writeln!(
        out,
        "// Minecraft {minecraft}). DO NOT EDIT BY HAND. Regenerate with LODESTONE_REGEN=1"
    );
    out.push_str("// (see the test module docs).\n");
    let _ = writeln!(
        out,
        "//! Generated entity-type id->name table for protocol {protocol} (Minecraft {minecraft}).\n//!"
    );
    out.push_str(
        "//! Maps the unified numeric entity-type id space to canonical\n\
         //! `minecraft:*` identifiers. Consumed by [`crate::entity_types`].\n\n",
    );
    render_table(&mut out, "ENTITY_TYPES", "ENTITY_TYPE_COUNT", pairs);
    out
}

